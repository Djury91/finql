-- Törzsadatok: fiókok, termékek, kereskedők, árfolyamok, üzleti nap.

CREATE TABLE bank.branches (
    branch_id  int  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       text NOT NULL UNIQUE CHECK (code ~ '^[A-Z]{3}[0-9]{2}$'),
    name       text NOT NULL,
    city       text NOT NULL,
    region     text NOT NULL
);

CREATE TABLE bank.products (
    product_id     int               GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_type   bank.product_type NOT NULL,
    name           text              NOT NULL UNIQUE,
    currency       char(3)           NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    interest_rate  numeric(6, 4)     NOT NULL CHECK (interest_rate >= 0)  -- éves kamat, törtként: 0.0690 = 6,9%
);

CREATE TABLE bank.merchants (
    merchant_id  bigint   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         text     NOT NULL,
    mcc          smallint NOT NULL CHECK (mcc BETWEEN 0 AND 9999),  -- Merchant Category Code (ISO 18245)
    category     text     NOT NULL,
    city         text     NOT NULL,
    country      char(2)  NOT NULL CHECK (country ~ '^[A-Z]{2}$')
);

-- MNB-középárfolyamok. Minden naptári napra van sor: hétvégén és ünnepnap az előző
-- munkanap árfolyama érvényes, így a napi JOIN sosem marad üresen. A HUF nem szerepel (1).
CREATE TABLE bank.fx_rates (
    rate_date    date           NOT NULL,
    currency     char(3)        NOT NULL CHECK (currency ~ '^[A-Z]{3}$' AND currency <> 'HUF'),
    rate_to_huf  numeric(12, 4) NOT NULL CHECK (rate_to_huf > 0),
    PRIMARY KEY (rate_date, currency)
);

-- Az aktuális üzleti nap (egysoros tábla). A késedelem és a „ma” ehhez mérődik, nem a
-- current_date-hez, így a szintetikus adatállomány hónapok múlva is ugyanazt mutatja.
CREATE TABLE bank.business_day (
    singleton      boolean PRIMARY KEY DEFAULT true CHECK (singleton),
    business_date  date    NOT NULL
);
