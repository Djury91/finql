-- Ügyfelek, számlák, kártyák.

CREATE TABLE bank.customers (
    customer_id     bigint                GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_type   bank.customer_type    NOT NULL,
    full_name       text                  NOT NULL,           -- PII
    birth_date      date,                                     -- PII; cégnél NULL
    tax_id          text                  NOT NULL UNIQUE,    -- PII: adóazonosító jel / adószám
    city            text                  NOT NULL,
    segment         bank.customer_segment NOT NULL,
    home_branch_id  int                   NOT NULL REFERENCES bank.branches,
    risk_rating     bank.risk_rating      NOT NULL,
    created_at      timestamptz           NOT NULL,

    CONSTRAINT customers_birth_date_ck
        CHECK ((customer_type = 'individual') = (birth_date IS NOT NULL)),
    CONSTRAINT customers_segment_ck CHECK (
        CASE customer_type
            WHEN 'individual' THEN segment IN ('retail', 'premium')
            ELSE segment IN ('sme', 'corporate')
        END
    ),
    -- Magánszemély: 10 jegyű adóazonosító jel (8-assal kezdődik). Cég: adószám 12345678-1-42 alakban.
    CONSTRAINT customers_tax_id_ck CHECK (
        CASE customer_type
            WHEN 'individual' THEN tax_id ~ '^8[0-9]{9}$'
            ELSE tax_id ~ '^[0-9]{8}-[1-5]-[0-9]{2}$'
        END
    )
);

CREATE TABLE bank.accounts (
    account_id    bigint              GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   bigint              NOT NULL REFERENCES bank.customers,
    product_id    int                 NOT NULL REFERENCES bank.products,
    branch_id     int                 NOT NULL REFERENCES bank.branches,
    iban          text                NOT NULL UNIQUE CHECK (iban ~ '^HU[0-9]{26}$'),  -- PII
    currency      char(3)             NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    status        bank.account_status NOT NULL,
    opened_at     date                NOT NULL,
    closed_at     date,
    credit_limit  numeric(18, 2)      CHECK (credit_limit > 0),  -- csak hitelkártyánál

    CONSTRAINT accounts_closed_ck CHECK ((status = 'closed') = (closed_at IS NOT NULL)),
    CONSTRAINT accounts_dates_ck  CHECK (closed_at >= opened_at),
    -- A tranzakciók (account_id, branch_id) párra hivatkoznak, így a denormalizált
    -- transactions.branch_id nem térhet el a számla fiókjától.
    CONSTRAINT accounts_account_branch_uq UNIQUE (account_id, branch_id)
);

CREATE TABLE bank.cards (
    card_id     bigint           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  bigint           NOT NULL REFERENCES bank.accounts,
    card_type   bank.card_type   NOT NULL,
    status      bank.card_status NOT NULL,
    issued_at   date             NOT NULL,
    expires_at  date             NOT NULL,
    last4       char(4)          NOT NULL CHECK (last4 ~ '^[0-9]{4}$'),

    CONSTRAINT cards_dates_ck CHECK (expires_at > issued_at)
);
