-- Hitelek és törlesztőrészletek. Egy hitelhez pontosan egy hitelszámla tartozik.

CREATE TABLE bank.loans (
    loan_id        bigint           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id     bigint           NOT NULL UNIQUE REFERENCES bank.accounts,
    principal      numeric(18, 2)   NOT NULL CHECK (principal > 0),
    interest_rate  numeric(6, 4)    NOT NULL CHECK (interest_rate >= 0),  -- éves, törtként
    term_months    smallint         NOT NULL CHECK (term_months > 0),
    start_date     date             NOT NULL,
    status         bank.loan_status NOT NULL
);

-- Annuitásos ütemezés: a teljes futamidő minden hónapjára van sor, a jövőbeliekre is.
-- Késedelmes az a részlet, amelynek due_date-je elmúlt, és amount_paid < amount_due.
CREATE TABLE bank.loan_installments (
    loan_id      bigint         NOT NULL REFERENCES bank.loans,
    seq          smallint       NOT NULL CHECK (seq > 0),
    due_date     date           NOT NULL,
    amount_due   numeric(18, 2) NOT NULL CHECK (amount_due > 0),
    amount_paid  numeric(18, 2) NOT NULL DEFAULT 0 CHECK (amount_paid BETWEEN 0 AND amount_due),
    paid_at      date,
    PRIMARY KEY (loan_id, seq),

    CONSTRAINT loan_installments_paid_ck CHECK ((paid_at IS NULL) = (amount_paid = 0))
);
